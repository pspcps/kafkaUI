import os
from playwright.sync_api import sync_playwright
BASE_URL = os.environ.get("DEMO_BASE_URL", "http://127.0.0.1:3001").rstrip("/")
with sync_playwright() as p:
 browser=p.chromium.launch(executable_path=os.environ.get('PLAYWRIGHT_CHROMIUM_EXECUTABLE'),headless=True,args=['--no-sandbox'])
 page=browser.new_page(viewport={'width':1440,'height':1000})
 errors=[]; calls=[]
 page.on('pageerror', lambda error: errors.append(str(error)))
 page.on('request', lambda request: calls.append(request.url) if '/api/' in request.url or ':8080' in request.url else None)
 page.goto(BASE_URL + '/clusters')
 page.get_by_text('Demo · Development',exact=True).first.wait_for()
 page.goto(BASE_URL + '/clusters/demo')
 page.get_by_text('Broker #1',exact=True).wait_for()
 page.goto(BASE_URL + '/clusters/demo/topics')
 page.get_by_text('demo.orders',exact=True).first.wait_for()
 page.get_by_placeholder('Search topics…').fill('payments')
 assert page.get_by_text('demo.orders',exact=True).count()==0
 page.get_by_placeholder('Search topics…').fill('')
 page.get_by_text('demo.orders',exact=True).first.click()
 page.get_by_role('button',name='Messages',exact=True).click()
 page.get_by_text('Showing 24 messages',exact=True).wait_for()
 page.get_by_role('button',name='Produce Message',exact=False).first.click()
 page.get_by_placeholder('message-key',exact=True).fill('preview-test')
 page.get_by_placeholder('{"key": "value"}',exact=True).fill('{"demo":true,"message":"Hosted preview test"}')
 page.locator('form').get_by_role('button',name='Produce Message',exact=True).click()
 page.get_by_text('Showing 25 messages',exact=True).wait_for()
 page.reload()
 page.get_by_role('button',name='Messages',exact=True).click()
 page.get_by_text('Showing 25 messages',exact=True).wait_for()
 page.goto(BASE_URL + '/jobs')
 page.get_by_text('Orders → Analytics',exact=True).wait_for()
 page.goto(BASE_URL + '/clusters/demo/topics')
 page.get_by_role('button',name='New Topic',exact=False).click()
 page.get_by_placeholder('my-topic',exact=True).fill('demo.created')
 page.get_by_role('button',name='Next',exact=True).click()
 page.get_by_role('button',name='Create Topic',exact=True).click()
 page.get_by_text('demo.created',exact=True).wait_for()
 page.reload()
 page.get_by_text('demo.created',exact=True).wait_for()
 page.get_by_role('button',name='Reset demo',exact=True).click()
 page.wait_for_url('**/clusters')
 page.goto(BASE_URL + '/clusters/demo/topics')
 page.get_by_text('demo.orders',exact=True).first.wait_for()
 assert page.get_by_text('demo.created',exact=True).count()==0
 print('Dashboard, search, messages, produce/persistence, jobs, create topic/persistence, reset passed')
 print('Errors:',errors)
 print('External API requests:',calls)
 assert not errors and not calls
 browser.close()
